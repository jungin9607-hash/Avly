def main():
    path = DATA / "adjustment_explanations.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    rules = json.loads((DATA / "adjustment_rules.json").read_text(encoding="utf-8"))
    labels = json.loads((DATA / "factor_labels.json").read_text(encoding="utf-8"))
    used = sorted({r["factor"] for t in rules.values() for r in t["rules"] if r["factor"].startswith("pdf_")})
    by_prefix = {f[4:10]: f for f in used}
    missing_text = sorted(set(by_prefix) - set(EXPLANATIONS))
    unknown = sorted(set(EXPLANATIONS) - set(by_prefix))
    if missing_text or unknown:
        raise SystemExit(f"쉬운 말이 없는 요소 {missing_text} / 규칙에 없는 키 {unknown}")
    added = 0
    for key, (title, easy, question, note) in EXPLANATIONS.items():
        factor = by_prefix[key]
        if factor in data["factors"]:
            continue
        entry = {"label": labels[factor], "title": title, "easy": easy, "question": question, "reviewed": False}
        if note:
            entry["note"] = note
        data["factors"][factor] = entry
        added += 1
    path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"쉬운 말 {added}개를 추가했습니다 (전체 요소 {len(data['factors'])}개)")


if __name__ == "__main__":
    main()
